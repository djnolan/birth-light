export const SHAPE_KEYS = ['bg3', 'bg2', 'bg1', 'eye', 'pupil'];

export function blendStates(a, b, t) {
  const out = {};
  for (const k of SHAPE_KEYS) {
    const A = a[k], B = b[k];
    out[k] = A.map((v, i) => v + (B[i] - v) * t);
  }
  out.pupilOpacity = a.pupilOpacity + (b.pupilOpacity - a.pupilOpacity) * t;
  return out;
}

// [x0,y0, c1x,c1y,c2x,c2y,x,y, ...] → "M… C… Z"
export function toPath(n, dx = 0, dy = 0) {
  let d = `M${(n[0] + dx).toFixed(1)},${(n[1] + dy).toFixed(1)}`;
  for (let i = 2; i < n.length; i += 6) {
    d += `C${(n[i] + dx).toFixed(1)},${(n[i + 1] + dy).toFixed(1)} ${(n[i + 2] + dx).toFixed(1)},${(n[i + 3] + dy).toFixed(1)} ${(n[i + 4] + dx).toFixed(1)},${(n[i + 5] + dy).toFixed(1)}`;
  }
  return d + 'Z';
}
