function normalizeRay(p) {
  const out = [];
  for (let i = 0; i < p.length; i += 2) {
    out.push(0.141989 * p[i] - 28.9941 - ART_W / 2, (p[i + 1] - 14437.4) / (15505.9 - 14437.4));
  }
  return out;
}

